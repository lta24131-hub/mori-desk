  static readonly Dictionary<string,FormatInfo> ById=All.ToDictionary(f=>f.Id,StringComparer.Ordinal);
  internal static bool IsTarget(string id){FormatInfo value;return id!=null&&ById.TryGetValue(id,out value)&&value.Writable;}
  internal static bool IsKnown(string id){return id!=null&&ById.ContainsKey(id);}
  internal static string Extension(string id){FormatInfo value;return id!=null&&ById.TryGetValue(id,out value)?value.Extensions[0]:"";}
  internal static string Label(string id){FormatInfo value;return id!=null&&ById.TryGetValue(id,out value)?value.Label:id??"";}
  internal static string FileExtension(string path){
   string name=Path.GetFileName(path);FormatInfo format;
   if(ById.TryGetValue(Detect(path),out format)){
    string match=format.Extensions.OrderByDescending(ext=>ext.Length).FirstOrDefault(ext=>name.EndsWith("."+ext,StringComparison.OrdinalIgnoreCase));
    if(match!=null)return name.Substring(name.Length-match.Length-1);
   }
   return Path.GetExtension(path);
  }
  internal static string NameWithoutExtension(string path){
   string name=Path.GetFileName(path),extension=FileExtension(path);
   return extension.Length==0?name:name.Substring(0,name.Length-extension.Length);
  }
  internal static string Detect(string path){
   if(string.IsNullOrWhiteSpace(path))return "";
   string name=Path.GetFileName(path).ToLowerInvariant();
   foreach(var format in All)foreach(string extension in format.Extensions)
    if(extension.Contains(".")&&name.EndsWith("."+extension,StringComparison.OrdinalIgnoreCase))return format.Id;
   string ext=Path.GetExtension(name).TrimStart('.');
   if(ext.Length==0)ext=name.TrimStart('.');
   foreach(var format in All)if(format.Extensions.Contains(ext,StringComparer.OrdinalIgnoreCase))return format.Id;
   return "";
  }
  internal static bool MatchesExtension(string path,string id){
   FormatInfo value;if(id==null||!ById.TryGetValue(id,out value)||string.IsNullOrWhiteSpace(path))return false;
   string name=Path.GetFileName(path);
   return value.Extensions.Any(extension=>name.EndsWith("."+extension,StringComparison.OrdinalIgnoreCase));
  }
